// Offline generator for the public demo's AI outputs (examples/luna-ai.json). Run on a developer machine only:
//   ANTHROPIC_API_KEY=... node scripts/ai-generate.mjs           calls the Claude API and rewrites examples/luna-ai.json
//   node scripts/ai-generate.mjs --dry                            prints the packs and prompt sizes, no API calls
// The site itself never calls a model: it reads the stored file and re-validates every item against today's evidence.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { MODEL, call, cost } from './ai-client.mjs';
const require = createRequire(import.meta.url);
const AI = require('../src/ai.cjs'), Demo = require('../src/demo.cjs'), template = require('../examples/luna-demo.json');

const OUT = new URL('../examples/luna-ai.json', import.meta.url);
// A fixed reference instant keeps runs reproducible; the packs use relative times, so any weekday gives the same fingerprints.
const NOW = new Date(process.env.DAYWEAVE_AI_NOW || '2026-10-22T12:00:00Z');
const PRESETS = [
  { key: 's1', en: 'Give Problem Set 4 two hours tomorrow afternoon', zh: '明天下午给 Problem Set 4 两小时' },
  { key: 's2', en: 'Block 45 minutes tonight at 21:00 for the team charter peer feedback', zh: '今晚 21:00 留 45 分钟写团队章程的同伴反馈' },
  { key: 's3', en: 'Find some time for the PRD', zh: '找点时间做 PRD' },
  { key: 's4', en: 'Invite my team to a memo meeting in three days at 16:00', zh: '邀请我的团队三天后 16:00 开备忘录会议' },
  { key: 's5', en: 'Spend 90 minutes on the interview synthesis in three days at 10:00', zh: '三天后 10:00 花 90 分钟做访谈整理' },
];

const d = Demo.resolve(template, NOW);
const jobs = [{ key: 'today', pack: AI.briefPack(d, NOW) }];
for (const a of d.assignments.filter(AI.breakable)) jobs.push({ key: a.id, pack: AI.breakdownPack(a, d, NOW) });
for (const p of PRESETS) for (const lang of AI.LANGS) jobs.push({ key: `${p.key}-${lang}`, pack: AI.proposePack(p[lang], d, NOW) });

if (process.argv.includes('--dry')) {
  for (const j of jobs) { const p = AI.prompt(j.pack); console.log(j.pack.task, j.key, AI.fingerprint(j.pack), `${p.system.length + p.user.length} chars`); }
  process.exit(0);
}

const items = [], usage = { input: 0, output: 0 }, served = new Set(), report = [];
for (const j of jobs) {
  let attempt = await call(j.pack), errors = attempt.output ? AI.validate(j.pack, attempt.output) : [`no output (${attempt.stop})`];
  const attempts = [{ stop: attempt.stop, errors }];
  // One repair round for the stored demo content; the evaluation (scripts/ai-eval.mjs) scores first attempts only.
  if (errors.length && attempt.output) {
    const prev = attempt;
    attempt = await call(j.pack, { output: prev.output, errors });
    errors = attempt.output ? AI.validate(j.pack, attempt.output) : [`no output (${attempt.stop})`];
    attempts.push({ stop: attempt.stop, errors });
    usage.input += prev.usage.input; usage.output += prev.usage.output; served.add(prev.model);
  }
  usage.input += attempt.usage.input; usage.output += attempt.usage.output; served.add(attempt.model);
  report.push(`${errors.length ? 'FAIL' : 'ok  '} ${j.pack.task} ${j.key} (${attempts.length} attempt${attempts.length > 1 ? 's' : ''})${errors.length ? ': ' + errors.join('; ') : ''}`);
  // A failing item is still stored so the site's validator rejects it visibly and falls back to the rules.
  items.push({ task: j.pack.task, key: j.key, fingerprint: AI.fingerprint(j.pack), output: attempt.output, attempts });
}

const costUSD = cost(usage);
const store = {
  schemaVersion: 1, synthetic: true, note: 'Pre-generated by scripts/ai-generate.mjs from the fictional Luna data. The site re-validates every item before showing it.',
  model: MODEL, servedModels: [...served], promptVersion: AI.VERSION, generatedAt: new Date().toISOString(), referenceNow: NOW.toISOString(),
  usage: { ...usage, costUSD }, presets: PRESETS, items,
};
fs.writeFileSync(OUT, JSON.stringify(store, null, 1) + '\n');
console.log(report.join('\n'));
console.log(`${items.length} items, ${usage.input} input + ${usage.output} output tokens, about US$${costUSD}`);
